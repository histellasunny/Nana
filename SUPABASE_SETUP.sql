-- Run this whole script once in Supabase: SQL Editor > New query > Run.
-- Anyone with the shared website link can read and add memos.
-- Public visitors cannot edit or delete existing posts through these policies.

create table if not exists public.travel_memos (
  id bigint generated by default as identity primary key,
  day integer not null check (day between 1 and 9),
  author text not null default 'Guest',
  title text not null default 'Travel memo',
  body text not null,
  created_at timestamptz not null default now()
);

-- Safe upgrade path if the earlier version of the table was created without a title column.
alter table public.travel_memos
  add column if not exists title text not null default 'Travel memo';

alter table public.travel_memos enable row level security;

-- Remove any broader default client privileges, then grant only what this page needs.
revoke all on table public.travel_memos from anon, authenticated;
revoke all on sequence public.travel_memos_id_seq from anon, authenticated;
grant select, insert on table public.travel_memos to anon;
grant usage, select on sequence public.travel_memos_id_seq to anon;

drop policy if exists "Anyone can read travel memos" on public.travel_memos;
drop policy if exists "Anyone can add travel memos" on public.travel_memos;

create policy "Anyone can read travel memos"
on public.travel_memos
for select
to anon
using (true);

create policy "Anyone can add travel memos"
on public.travel_memos
for insert
to anon
with check (
  day between 1 and 9
  and char_length(trim(author)) between 1 and 40
  and char_length(trim(title)) between 1 and 80
  and char_length(trim(body)) between 1 and 2000
);
